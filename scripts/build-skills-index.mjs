#!/usr/bin/env node
/* Generate SKILLS.md index from skill frontmatter.
 *
 * Usage:
 *   node scripts/build-skills-index.mjs --workspace-dir <dir> --template-dir <dir>
 *
 * Reads:
 *   <template-dir>/skills/*.md      (universal skills)
 *   <template-dir>/domain/skills/*.md (domain-scoped skills)
 *   <workspace-dir>/skills/*.md     (installed domain skills, takes precedence)
 *
 * Writes:
 *   <workspace-dir>/SKILLS.md
 */

import fs from "node:fs";
import path from "node:path";

const args = process.argv.slice(2);
const opts = {};
for (let i = 0; i < args.length; i += 1) {
  const arg = args[i];
  if (!arg.startsWith("--")) usage();
  opts[arg.slice(2)] = args[i + 1];
  i += 1;
}

if (!opts["workspace-dir"] || !opts["template-dir"]) usage();

const workspaceDir = path.resolve(opts["workspace-dir"]);
const templateDir = path.resolve(opts["template-dir"]);

const universal = collect(path.join(templateDir, "skills"));
const domainTemplate = collect(path.join(templateDir, "domain", "skills"));
const installed = collect(path.join(workspaceDir, "skills"));

const installedNames = new Set(installed.map((s) => s.name));
const domainSkills = installed.length
  ? installed
  : domainTemplate.filter((s) => !installedNames.has(s.name));

const out = render(universal, domainSkills);
fs.mkdirSync(workspaceDir, { recursive: true });
fs.writeFileSync(path.join(workspaceDir, "SKILLS.md"), out, "utf8");
console.log(`Wrote ${path.join(workspaceDir, "SKILLS.md")}`);

function collect(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".md"))
    .map((f) => parseSkill(path.join(dir, f)))
    .filter(Boolean)
    .sort((a, b) => a.name.localeCompare(b.name));
}

function parseSkill(file) {
  const content = fs.readFileSync(file, "utf8");
  const fm = content.match(/^---\n([\s\S]*?)\n---/);
  if (!fm) return null;
  const meta = {};
  for (const line of fm[1].split("\n")) {
    const m = line.match(/^([a-zA-Z0-9_-]+):\s*(.+)$/);
    if (m) meta[m[1].trim()] = m[2].trim();
  }
  if (!meta.name) return null;
  return {
    name: meta.name,
    description: meta.description || "",
    file: path.basename(file),
    relPath: path.basename(path.dirname(file)) + "/" + path.basename(file),
  };
}

function render(universal, domainSkills) {
  const today = new Date().toISOString().slice(0, 10);
  const lines = [
    `# SKILLS.md - Skill Index`,
    "",
    `Generated by install.sh on ${today}. Re-run install.sh to refresh.`,
    "",
    `Skills are loaded by the routing table in AGENTS.md. This index lists which skills exist and when each loads — it is documentation, not configuration.`,
    "",
    "## Universal Skills",
    "",
    "Available across every domain.",
    "",
    "| Skill | When it loads |",
    "|-------|---------------|",
  ];
  for (const s of universal) {
    lines.push(`| \`${s.name}.md\` | ${oneLine(s.description)} |`);
  }
  lines.push("");
  lines.push("## Domain Skills");
  lines.push("");
  if (!domainSkills.length) {
    lines.push("*No domain skills installed yet. Add `.md` files with `name`/`description` frontmatter to `~/.openclaw/workspaces/<domain>/skills/`.*");
  } else {
    lines.push("Loaded from this domain's workspace.");
    lines.push("");
    lines.push("| Skill | When it loads |");
    lines.push("|-------|---------------|");
    for (const s of domainSkills) {
      lines.push(`| \`${s.name}.md\` | ${oneLine(s.description)} |`);
    }
  }
  lines.push("");
  lines.push("## Adding a Skill");
  lines.push("");
  lines.push("1. Create a new `.md` file in the skills directory with `name:` and `description:` frontmatter.");
  lines.push("2. Add a routing row in `AGENTS.md` that lists the new skill in the **Load Skills** column.");
  lines.push("3. Re-run `install.sh` (or `node scripts/build-skills-index.mjs --workspace-dir ... --template-dir ...`) to refresh this index.");
  lines.push("");
  return lines.join("\n");
}

function oneLine(s) {
  return String(s).replace(/\n/g, " ").replace(/\|/g, "\\|").trim();
}

function usage() {
  console.error("Usage: node scripts/build-skills-index.mjs --workspace-dir <dir> --template-dir <dir>");
  process.exit(2);
}
